/// Java's `OperationCategory`: maps an `/api/v1/` namespace to a category
/// tool. The AI category is handled separately by `stirling_ai`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum PdfCategory {
    Convert,
    Pages,
    Misc,
    Security,
}

impl PdfCategory {
    const ALL: [Self; 4] = [Self::Convert, Self::Pages, Self::Misc, Self::Security];

    fn url_prefix(self) -> &'static str {
        match self {
            Self::Convert => "/api/v1/convert/",
            Self::Pages => "/api/v1/general/",
            Self::Misc => "/api/v1/misc/",
            Self::Security => "/api/v1/security/",
        }
    }

    fn tool_name(self) -> &'static str {
        match self {
            Self::Convert => "stirling_convert",
            Self::Pages => "stirling_pages",
            Self::Misc => "stirling_misc",
            Self::Security => "stirling_security",
        }
    }

    /// Tool descriptions, verbatim from Java's category tool classes.
    fn tool_description(self) -> &'static str {
        match self {
            Self::Convert => {
                "Convert files between PDF and other formats (PDF<->Word, PDF<->image, HTML->PDF, etc.). Inspect the `operation` enum, then call stirling_describe_operation with the chosen op to get its parameters JSON Schema before calling this tool."
            }
            Self::Pages => {
                "Manipulate PDF pages: merge, split, rotate, rearrange, crop, delete, overlay, add blank pages. Call stirling_describe_operation with the chosen op to get its parameters schema before invoking this tool."
            }
            Self::Misc => {
                "Miscellaneous PDF operations: compress, OCR, stamp / watermark, edit metadata, flatten, repair, and similar utilities. Call stirling_describe_operation with the chosen op to get its parameters schema before invoking this tool."
            }
            Self::Security => {
                "Security-related PDF operations: password add/remove, redact, sanitize, certify / sign with cert, validate signature, add watermark. Call stirling_describe_operation with the chosen op to get its parameters schema before invoking this tool."
            }
        }
    }
}

/// One MCP-exposable PDF operation derived from the generated catalog, the
/// Rust analogue of Java's `OperationMeta` for `JAVA_ENDPOINT` targets.
#[derive(Debug)]
struct PdfOperation {
    id: String,
    category: PdfCategory,
    endpoint_path: String,
    summary: String,
    parameters_schema: Value,
}

/// PDF operations keyed by id, derived once from the compiled-in catalog plus
/// its MCP supplement (together covering every flat path Java's
/// `McpToolCatalog.discover` indexes) with Java's `extractOpId` semantics: the
/// op id is the flat URL tail only, so nested or parametrised tails are
/// skipped. Every Java convert endpoint is nested (`/convert/pdf/word`), so -
/// exactly as in Java - the `stirling_convert` enum is genuinely empty.
/// Java's `putIfAbsent` (first-handler-wins) duplicate rule maps to
/// first-wins in merged path order; catalog ids are currently unique so it
/// never triggers.
static PDF_OPERATIONS: LazyLock<BTreeMap<String, PdfOperation>> = LazyLock::new(|| {
    let Ok(mut catalog) = serde_json::from_str::<BTreeMap<String, Value>>(OPERATION_CATALOG_JSON)
    else {
        return BTreeMap::new();
    };
    let supplement = serde_json::from_str::<BTreeMap<String, Value>>(OPERATION_SUPPLEMENT_JSON)
        .unwrap_or_default();
    for (path, schema) in supplement {
        catalog.entry(path).or_insert(schema);
    }
    let mut operations = BTreeMap::new();
    for (path, schema) in catalog {
        let Some((category, id)) = PdfCategory::ALL.iter().find_map(|category| {
            let tail = path.strip_prefix(category.url_prefix())?;
            (!tail.trim().is_empty() && !tail.contains('/') && !tail.contains('{'))
                .then(|| (*category, tail.to_owned()))
        }) else {
            continue;
        };
        // Java prefers the `@Operation` summary; the generated catalog does
        // not carry it, so use the request-model description when present and
        // fall back to Java's prettified id otherwise.
        let summary = schema
            .get("description")
            .and_then(Value::as_str)
            .map_or_else(|| id.replace('-', " "), str::to_owned);
        operations.entry(id.clone()).or_insert(PdfOperation {
            id,
            category,
            endpoint_path: path,
            summary,
            parameters_schema: schema,
        });
    }
    operations
});

#[derive(Clone)]
struct McpState {
    config: McpConfig,
    store: Arc<SecurityStore>,
    catalog: Arc<AiCapabilityCatalog>,
    job_manager: Arc<JobManager>,
    dispatch_router: Router,
    runtime_config: Arc<RuntimeConfig>,
    /// `Some` when the `OAuth2` resource-server chain is active (any
    /// `mcp.auth.mode` other than exactly `apikey`, mirroring Java's
    /// `isApiKeyMode`); `None` in API-key mode.
    oauth: Option<Arc<McpOAuthVerifier>>,
}

/// Per-call identity and granted scopes — Java's `McpCallContext`. In API-key
/// mode every valid key is statically granted both tool scopes
/// (`McpApiKeyAuthFilter` parity); in OAuth mode the grant is the validated
/// token's real `scope` claim, so per-tool checks genuinely gate callers.
#[derive(Clone, Debug)]
struct McpCallContext {
    auth: AuthContext,
    scopes_enabled: bool,
    granted_scopes: BTreeSet<String>,
}

impl McpCallContext {
    /// The static both-scopes grant Java's API-key filter attaches to every
    /// valid key.
    fn for_api_key(auth: AuthContext, scopes_enabled: bool) -> Self {
        Self {
            auth,
            scopes_enabled,
            granted_scopes: BTreeSet::from([READ_SCOPE.to_owned(), WRITE_SCOPE.to_owned()]),
        }
    }

    /// Java `McpCallContext.hasScope`: everything passes while scope
    /// enforcement is off or the requirement is blank; otherwise the scope
    /// must have been granted.
    fn has_scope(&self, required: &str) -> bool {
        !self.scopes_enabled || required.trim().is_empty() || self.granted_scopes.contains(required)
    }
}

