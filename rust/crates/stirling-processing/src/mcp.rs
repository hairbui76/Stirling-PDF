/// Builds the MCP router in the configured authentication mode. Mirroring
/// Java's `McpSecurityConfig.mcpSecurityFilterChain`, `apikey` (exact,
/// case-insensitive) mounts the API-key chain, and **every other mode value —
/// including blank or a near-miss like `api-key` — mounts the `OAuth2`
/// resource-server chain**, which also claims the RFC 9728 protected-resource
/// metadata paths.
pub(crate) fn routes(
    config: McpConfig,
    store: Arc<SecurityStore>,
    engine_settings: &AiCommentEngineSettings,
    job_manager: Arc<JobManager>,
    dispatch_router: Router,
    runtime_config: Arc<RuntimeConfig>,
) -> Router {
    if !config.enabled {
        return Router::new();
    }
    let api_key_mode = config.auth.mode.trim().eq_ignore_ascii_case("apikey");
    let oauth = if api_key_mode {
        None
    } else {
        log_oauth_config_findings(&config);
        Some(Arc::new(McpOAuthVerifier::from_config(&config)))
    };
    let catalog = Arc::new(AiCapabilityCatalog::new(
        EngineConnection::from_settings(engine_settings),
        config.engine_capability_refresh_minutes,
    ));
    let oauth_mode = oauth.is_some();
    let state = Arc::new(McpState {
        config,
        store,
        catalog,
        job_manager,
        dispatch_router,
        runtime_config,
        oauth,
    });
    let mut router = Router::new().route(MCP_PATH, post(handle));
    if oauth_mode {
        // RFC 9728 section 3.1: the path-inserted form for a resource with a
        // path component ({metadata}/mcp) plus the bare document — Java claims
        // both (and all subpaths) in its OAuth chain's security matcher.
        router = router
            .route(
                PROTECTED_RESOURCE_METADATA_PATH,
                get(protected_resource_metadata_handler),
            )
            .route(
                "/.well-known/oauth-protected-resource/{*resource}",
                get(protected_resource_metadata_handler),
            );
    }
    router.with_state(state)
}

/// Startup findings for the OAuth chain, a condensed port of Java's
/// `McpConfigValidator` WARN cases so a fail-closed misconfiguration shows up
/// in the logs instead of as a later rejected-token 401.
fn log_oauth_config_findings(config: &McpConfig) {
    let auth = &config.auth;
    let mode = auth.mode.trim();
    if !mode.is_empty() && !mode.eq_ignore_ascii_case("oauth") {
        warn!(
            mode = auth.mode,
            "mcp.auth.mode is not recognized (expected 'oauth' or 'apikey'); it falls back to the \
             OAuth chain, which rejects every token unless issuer-uri and resource-id are set. A \
             near-miss like 'api-key' is NOT treated as API-key mode."
        );
    }
    if auth.issuer_uri.trim().is_empty() {
        warn!(
            "mcp.auth.issuer-uri is not set: the JWT validator fails closed and rejects every \
             token."
        );
    }
    if auth.resource_id.trim().is_empty()
        && !auth
            .accepted_audiences
            .iter()
            .any(|audience| !audience.trim().is_empty())
    {
        warn!(
            "neither mcp.auth.resource-id nor mcp.auth.accepted-audiences is set: the audience \
             validator fails closed and rejects every token (RFC 8707)."
        );
    }
    if !auth.require_existing_account {
        warn!(
            "mcp.auth.require-existing-account=false is not honored by the Rust MCP boundary: a \
             validated token subject must still resolve to a provisioned, enabled Stirling \
             account (fail-closed divergence documented in rust/contracts/mcp.md)."
        );
    }
}

/// Serves the RFC 9728 protected-resource metadata document (GET, no
/// authentication), Java's Spring `OAuth2ProtectedResourceMetadataFilter` +
/// `buildResourceMetadata` customizer.
async fn protected_resource_metadata_handler(
    State(state): State<Arc<McpState>>,
    uri: Uri,
    headers: HeaderMap,
) -> Response {
    json_response(
        StatusCode::OK,
        mcp_oauth::protected_resource_metadata(&state.config, &headers, uri.path()),
    )
}

async fn handle(State(state): State<Arc<McpState>>, request: Request) -> Response {
    let (parts, body) = request.into_parts();
    if !is_json_content_type(&parts.headers) {
        return StatusCode::UNSUPPORTED_MEDIA_TYPE.into_response();
    }
    if declared_body_too_large(&parts.headers, state.config.max_request_bytes) {
        return payload_too_large(state.config.max_request_bytes);
    }
    let Ok(body) = to_bytes(body, state.config.max_request_bytes).await else {
        return payload_too_large(state.config.max_request_bytes);
    };
    let context = match authenticate(&state, &parts.headers).await {
        Ok(context) => context,
        Err(response) => return response,
    };
    let Ok(body) = serde_json::from_slice::<Value>(&body) else {
        return json_response(
            StatusCode::BAD_REQUEST,
            rpc_failure(Value::Null, -32700, "Request body is not valid JSON"),
        );
    };
    let Some(request) = decode_request(&body) else {
        return json_response(
            StatusCode::BAD_REQUEST,
            rpc_failure(
                Value::Null,
                -32600,
                "Body is not a valid JSON-RPC 2.0 request",
            ),
        );
    };
    if request.notification {
        return StatusCode::NO_CONTENT.into_response();
    }
    let result = dispatch(&state, &context, &request).await;
    json_response(StatusCode::OK, result)
}

struct RpcRequest {
    id: Value,
    method: String,
    params: Option<Value>,
    notification: bool,
}

fn decode_request(body: &Value) -> Option<RpcRequest> {
    let object = body.as_object()?;
    if object.get("jsonrpc")?.as_str()? != "2.0" {
        return None;
    }
    let method = object.get("method")?.as_str()?.to_owned();
    let id = object.get("id").cloned().unwrap_or(Value::Null);
    Some(RpcRequest {
        notification: id.is_null(),
        id,
        method,
        params: object.get("params").cloned(),
    })
}

async fn dispatch(state: &McpState, context: &McpCallContext, request: &RpcRequest) -> Value {
    match request.method.as_str() {
        "initialize" => rpc_success(
            request.id.clone(),
            initialize_result(request.params.as_ref()),
        ),
        "tools/list" => {
            let operations = visible_operations(state).await;
            rpc_success(request.id.clone(), tools_list_result(state, &operations))
        }
        "tools/call" => handle_tools_call(state, context, request).await,
        "ping" | "notifications/initialized" => {
            rpc_success(request.id.clone(), Value::Object(Map::new()))
        }
        method => rpc_failure(
            request.id.clone(),
            -32601,
            &format!("Method not found: {method}"),
        ),
    }
}

fn initialize_result(params: Option<&Value>) -> Value {
    let requested = params
        .and_then(|params| params.get("protocolVersion"))
        .and_then(Value::as_str);
    let negotiated = requested
        .filter(|requested| SUPPORTED_PROTOCOL_VERSIONS.contains(requested))
        .unwrap_or(PREFERRED_PROTOCOL_VERSION);
    json!({
        "protocolVersion": negotiated,
        "capabilities": {"tools": {}},
        "serverInfo": {
            "name": "stirling-pdf-mcp",
            "version": application_version(),
        }
    })
}

async fn handle_tools_call(
    state: &McpState,
    context: &McpCallContext,
    request: &RpcRequest,
) -> Value {
    let Some(params) = request.params.as_ref().and_then(Value::as_object) else {
        return rpc_failure(request.id.clone(), -32602, "Missing params for tools/call");
    };
    let Some(name) = params.get("name").and_then(Value::as_str) else {
        return rpc_failure(request.id.clone(), -32602, "Missing tool name");
    };
    let arguments = params
        .get("arguments")
        .cloned()
        .unwrap_or_else(|| Value::Object(Map::new()));
    let operations = visible_operations(state).await;
    let result = match name {
        "stirling_describe_operation" => describe_operation(state, &arguments, &operations),
        "stirling_ai" => call_ai(state, context, &arguments, &operations).await,
        "stirling_upload" => upload_file(state, context, &arguments).await,
        "stirling_download" => download_file(state, context, &arguments).await,
        "stirling_pages" => call_category(state, context, PdfCategory::Pages, &arguments).await,
        "stirling_convert" => call_category(state, context, PdfCategory::Convert, &arguments).await,
        "stirling_misc" => call_category(state, context, PdfCategory::Misc, &arguments).await,
        "stirling_security" => {
            call_category(state, context, PdfCategory::Security, &arguments).await
        }
        "stirling_operation" => run_operation(state, context, &arguments).await,
        _ => {
            return rpc_failure(request.id.clone(), -32602, &format!("Unknown tool: {name}"));
        }
    };
    rpc_success(request.id.clone(), result)
}

/// The category's operations as currently visible: allow/block-list filtered
/// (by op id, matching Java) and endpoint-enabled filtered the way Java uses
/// `EndpointConfiguration.isEndpointEnabledForUri`; sorted by id.
fn enabled_pdf_operations(state: &McpState, category: PdfCategory) -> Vec<&'static PdfOperation> {
    PDF_OPERATIONS
        .values()
        .filter(|operation| operation.category == category)
        .filter(|operation| operation_allowed(&state.config, &operation.id))
        .filter(|operation| {
            state
                .runtime_config
                .is_endpoint_enabled_for_uri(&operation.endpoint_path)
        })
        .collect()
}

/// Java `McpToolCatalog.findByOperationId` for the PDF slice: a blocked or
/// endpoint-disabled PDF operation is `Hidden`, never absent - it must not
/// fall through to a same-id AI capability.
enum PdfLookup {
    Enabled(&'static PdfOperation),
    Hidden,
    Unknown,
}

fn find_pdf_operation(state: &McpState, id: &str) -> PdfLookup {
    let Some(operation) = PDF_OPERATIONS.get(id) else {
        return PdfLookup::Unknown;
    };
    if operation_allowed(&state.config, id)
        && state
            .runtime_config
            .is_endpoint_enabled_for_uri(&operation.endpoint_path)
    {
        PdfLookup::Enabled(operation)
    } else {
        PdfLookup::Hidden
    }
}

/// Runs one category tool call with Java `AbstractCategoryTool.call` semantics:
/// a missing, unknown, wrong-category, blocked, or endpoint-disabled operation
/// returns the category's operation-list error, and — in Java's exact order,
/// after the operation resolves — the caller must hold the operation's
/// required scope (`mcp.tools.write` for every PDF operation). API keys carry
/// both scopes statically; OAuth callers are gated by their token's real
/// `scope` claim.
async fn call_category(
    state: &McpState,
    context: &McpCallContext,
    category: PdfCategory,
    arguments: &Value,
) -> Value {
    let Some(operation_id) = operation_argument(arguments) else {
        return operation_list_error(state, category, None);
    };
    let operation = match find_pdf_operation(state, operation_id) {
        PdfLookup::Enabled(operation) if operation.category == category => operation,
        _ => return operation_list_error(state, category, Some(operation_id)),
    };
    if !context.has_scope(WRITE_SCOPE) {
        return tool_error(&format!(
            "Insufficient scope: this operation requires '{WRITE_SCOPE}'."
        ));
    }
    dispatch_operation(
        state,
        context,
        arguments,
        &operation.endpoint_path,
        &operation.id,
    )
    .await
}

/// Java `AbstractCategoryTool.operationListError`: the error for a missing or
/// unknown operation, listing this category's available ids and summaries.
fn operation_list_error(state: &McpState, category: PdfCategory, bad_op_id: Option<&str>) -> Value {
    let mut message = match bad_op_id {
        None => format!(
            "Missing required argument 'operation' for {}",
            category.tool_name()
        ),
        Some(bad_op_id) => format!(
            "Unknown or disabled operation '{bad_op_id}' for {}",
            category.tool_name()
        ),
    };
    let operations = enabled_pdf_operations(state, category);
    if operations.is_empty() {
        message.push_str(". No operations are currently available in this category.");
    } else {
        message.push_str(". Available operations:");
        for operation in &operations {
            message.push_str("\n- ");
            message.push_str(&operation.id);
            message.push_str(" - ");
            message.push_str(&operation.summary);
        }
        message.push_str("\nRe-call this tool with a valid 'operation'.");
    }
    tool_error(&message)
}

async fn visible_operations(state: &McpState) -> BTreeMap<String, AiCapability> {
    state
        .catalog
        .snapshot()
        .await
        .into_iter()
        .filter(|(id, _)| operation_allowed(&state.config, id))
        .collect()
}

fn operation_allowed(config: &McpConfig, id: &str) -> bool {
    if config
        .blocked_operations
        .iter()
        .any(|blocked| blocked == id)
    {
        return false;
    }
    config.allowed_operations.is_empty()
        || config
            .allowed_operations
            .iter()
            .any(|allowed| allowed == id)
}

