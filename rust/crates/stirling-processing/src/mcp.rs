/// Trimmed text argument, matching Java's `McpToolSupport.textArg` (used for
/// `file`, `fileName`, and `fileId`).
fn text_argument<'a>(arguments: &'a Value, name: &str) -> Option<&'a str> {
    arguments
        .get(name)
        .and_then(Value::as_str)
        .map(str::trim)
        .filter(|value| !value.is_empty())
}

/// The `operation` argument exactly as Java's category/describe/AI tools read
/// it (`JsonNode.asText()` with only a blank check): a blank value counts as
/// missing, but a padded value such as `" rotate-pdf "` is looked up
/// untrimmed - and therefore fails - rather than being trimmed first.
fn operation_argument(arguments: &Value) -> Option<&str> {
    arguments
        .get("operation")
        .and_then(Value::as_str)
        .filter(|value| !value.trim().is_empty())
}

fn json_response(status: StatusCode, body: Value) -> Response {
    (status, axum::Json(body)).into_response()
}

