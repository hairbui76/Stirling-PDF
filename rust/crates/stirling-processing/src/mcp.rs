    #[tokio::test]
    async fn operation_argument_is_looked_up_untrimmed_like_java()
    -> Result<(), Box<dyn std::error::Error>> {
        let directory = tempfile::tempdir()?;
        let state = stub_state(directory.path(), axum::Router::new(), 1024)?;
        let context = test_context();

        // Java reads the id via JsonNode.asText() without trimming, so a
        // padded id fails the lookup and is quoted verbatim in the error.
        let padded = call_category(
            &state,
            &context,
            PdfCategory::Pages,
            &json!({"operation": " rotate-pdf "}),
        )
        .await;
        assert_eq!(padded["isError"], true);
        assert!(padded["content"][0]["text"].as_str().is_some_and(|text| {
            text.starts_with("Unknown or disabled operation ' rotate-pdf ' for stirling_pages.")
        }));

        // A blank id counts as missing, exactly like Java's isBlank check.
        let blank = call_category(
            &state,
            &context,
            PdfCategory::Pages,
            &json!({"operation": "   "}),
        )
        .await;
        assert!(blank["content"][0]["text"].as_str().is_some_and(|text| {
            text.starts_with("Missing required argument 'operation' for stirling_pages.")
        }));

        // stirling_describe_operation shares the same untrimmed rule.
        let described = describe_operation(
            &state,
            &json!({"operation": " rotate-pdf "}),
            &BTreeMap::new(),
        );
        assert_eq!(
            described["content"][0]["text"],
            "Unknown or disabled operation:  rotate-pdf "
        );
        Ok(())
    }

    #[tokio::test]
    async fn category_dispatch_reports_json_file_oversized_and_unrouted_results()
    -> Result<(), Box<dyn std::error::Error>> {
        use axum::routing::post;
        let context = test_context();
        let arguments = json!({
            "operation": "rotate-pdf",
            "file": STANDARD.encode(b"fake input bytes"),
        });

        // A JSON response is a structured report returned inline as text.
        let directory = tempfile::tempdir()?;
        let json_router = axum::Router::new().route(
            "/api/v1/general/rotate-pdf",
            post(|| async {
                (
                    [(header::CONTENT_TYPE, "application/json")],
                    r#"{"report":true}"#,
                )
            }),
        );
        let state = stub_state(directory.path(), json_router, 1024 * 1024)?;
        let result = call_category(&state, &context, PdfCategory::Pages, &arguments).await;
        assert_eq!(result.get("isError"), None);
        assert_eq!(result["content"][0]["text"], r#"{"report":true}"#);

        // A small binary response is stored and inlined as a resource block.
        let directory = tempfile::tempdir()?;
        let file_router = axum::Router::new().route(
            "/api/v1/general/rotate-pdf",
            post(|| async { ([(header::CONTENT_TYPE, "application/pdf")], vec![7_u8; 64]) }),
        );
        let state = stub_state(directory.path(), file_router.clone(), 1024 * 1024)?;
        let result = call_category(&state, &context, PdfCategory::Pages, &arguments).await;
        assert_eq!(result.get("isError"), None);
        let text = result["content"][0]["text"].as_str().unwrap_or_default();
        // No Content-Disposition upstream: the op id names the file, exactly
        // like Java's buildResult fallback to meta.id().
        assert!(text.starts_with("rotate-pdf succeeded. Result: rotate-pdf (64 bytes)"));
        assert!(text.contains("The file is included inline below."));
        assert_eq!(
            result["content"][1]["resource"]["mimeType"],
            "application/pdf"
        );
        let blob = result["content"][1]["resource"]["blob"]
            .as_str()
            .unwrap_or_default();
        assert_eq!(STANDARD.decode(blob)?, vec![7_u8; 64]);

        // Over the inline limit: fileId-only message, no resource block.
        let directory = tempfile::tempdir()?;
        let state = stub_state(directory.path(), file_router, 8)?;
        let result = call_category(&state, &context, PdfCategory::Pages, &arguments).await;
        assert_eq!(result.get("isError"), None);
        assert_eq!(result["content"].as_array().map(Vec::len), Some(1));
        assert!(
            result["content"][0]["text"]
                .as_str()
                .is_some_and(|text| text
                    .contains("Large result - fetch it with stirling_download"))
        );

        // A catalog op whose route the Rust router does not implement fails
        // at dispatch with the op's HTTP status (documented in the contract).
        let directory = tempfile::tempdir()?;
        let state = stub_state(directory.path(), axum::Router::new(), 1024)?;
        let result = call_category(&state, &context, PdfCategory::Pages, &arguments).await;
        assert_eq!(result["isError"], true);
        assert!(
            result["content"][0]["text"]
                .as_str()
                .is_some_and(|text| text.starts_with("rotate-pdf failed: HTTP 404"))
        );
        Ok(())
    }

    #[tokio::test]
    async fn per_scope_gating_matches_java_tool_checks_and_order()
    -> Result<(), Box<dyn std::error::Error>> {
        let directory = tempfile::tempdir()?;
        let state = stub_state(directory.path(), axum::Router::new(), 1024)?;

        // Every PDF operation is a write; a read-only caller is refused with
        // Java's AbstractCategoryTool message, AFTER the operation resolves.
        let read_only = scoped_context(&["mcp.tools.read"]);
        let refused = call_category(
            &state,
            &read_only,
            PdfCategory::Pages,
            &json!({"operation": "rotate-pdf"}),
        )
        .await;
        assert_eq!(refused["isError"], true);
        assert_eq!(
            refused["content"][0]["text"],
            "Insufficient scope: this operation requires 'mcp.tools.write'."
        );
        // Java's order: an unknown operation reports the operation-list error,
        // never the scope error, even for an unprivileged caller.
        let unknown = call_category(
            &state,
            &read_only,
            PdfCategory::Pages,
            &json!({"operation": "nope"}),
        )
        .await;
        assert!(unknown["content"][0]["text"].as_str().is_some_and(|text| {
            text.starts_with("Unknown or disabled operation 'nope' for stirling_pages.")
        }));

        let upload = upload_file(
            &state,
            &read_only,
            &json!({"file": STANDARD.encode(b"bytes")}),
        )
        .await;
        assert_eq!(
            upload["content"][0]["text"],
            "Insufficient scope: stirling_upload requires 'mcp.tools.write'."
        );

        let write_only = scoped_context(&["mcp.tools.write"]);
        let download = download_file(&state, &write_only, &json!({"fileId": "abc"})).await;
        assert_eq!(
            download["content"][0]["text"],
            "Insufficient scope: stirling_download requires 'mcp.tools.read'."
        );

        let operation = run_operation(
            &state,
            &read_only,
            &json!({"operation": "/api/v1/general/rotate-pdf"}),
        )
        .await;
        assert_eq!(
            operation["content"][0]["text"],
            "Insufficient scope: this operation requires 'mcp.tools.write'."
        );

        // mcp.scopesEnabled=false disables the gate entirely (Java hasScope).
        let ungated = McpCallContext {
            auth: test_auth_context(),
            scopes_enabled: false,
            granted_scopes: BTreeSet::new(),
        };
        let download = download_file(&state, &ungated, &json!({"fileId": "abc"})).await;
        assert!(
            download["content"][0]["text"]
                .as_str()
                .is_some_and(|text| { text.starts_with("Unknown or inaccessible fileId") })
        );
        Ok(())
    }

